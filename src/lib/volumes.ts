// Voxel dimensions for a volume, keyed by its public URL in the manifest.
export interface VolumeDimensions {
  width: number;
  height: number;
  depth: number;
}

type VolumeManifest = Record<string, VolumeDimensions>;

// The site is deployed under a sub-path (GitHub Pages project site), so
// public assets must be prefixed with the configured `base`. `BASE_URL` does
// not always include a trailing slash, so normalize it before joining paths.
const BASE_URL = import.meta.env.BASE_URL.replace(/\/?$/, "/");

// Resolve a base-relative public path (e.g. "/volumes/x.raw.zst") to a full
// URL that includes the deployment base path.
export function resolveVolumeUrl(path: string): string {
  return `${BASE_URL}${path.replace(/^\//, "")}`;
}

// The manifest is generated by preprocessing/convert-volumes.py and served
// alongside the .raw.zst files. Cache the in-flight/settled request so every
// viewer shares a single fetch.
let manifestPromise: Promise<VolumeManifest> | null = null;

function loadManifest(): Promise<VolumeManifest> {
  if (!manifestPromise) {
    manifestPromise = fetch(resolveVolumeUrl("/volumes/manifest.json"))
      .then((response) => {
        if (!response.ok) {
          throw new Error(
            `Failed to load volume manifest (HTTP ${response.status}).`,
          );
        }
        return response.json() as Promise<VolumeManifest>;
      })
      .catch((error) => {
        // Allow a later attempt to retry instead of caching the failure.
        manifestPromise = null;
        throw error;
      });
  }
  return manifestPromise;
}

export async function loadVolumeDimensions(
  url: string,
): Promise<VolumeDimensions> {
  const manifest = await loadManifest();
  const dimensions = manifest[url];
  if (!dimensions) {
    throw new Error(`No dimensions found for volume "${url}".`);
  }
  return dimensions;
}
